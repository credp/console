#!/usr/bin/env bash
# Bootstrap a DE10-Nano (Cyclone V SoC) development host.
#
# Supported host: x86_64 Debian/Ubuntu.  The script installs the open-source
# build/debug tools and configures an existing Altera Quartus Prime Lite 25.1std
# installation. Download Quartus and Cyclone V device support separately.
# See DE10_NANO_SETUP.md in this directory before running this script.

set -Eeuo pipefail

readonly SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
readonly ENV_FILE="${SCRIPT_DIR}/de10-nano-env.sh"
readonly UDEV_RULE_FILE="/etc/udev/rules.d/51-usbblaster.rules"

QUARTUS_ROOT="${QUARTUS_ROOTDIR:-}"
INSTALL_PACKAGES=1
INSTALL_UDEV=1

usage() {
    cat <<'EOF'
Usage: ./setup.sh [options]

Options:
  --quartus-root DIR   Quartus directory containing bin/quartus_sh
  --skip-packages      Do not install host packages
  --skip-udev          Do not install the USB-Blaster udev rule
  -h, --help           Show this help

Examples:
  ./setup.sh
  ./setup.sh --quartus-root "$HOME/altera/25.1std/quartus"

After setup, start a development shell with:
  source ./de10-nano-env.sh
EOF
}

die() {
    printf 'setup.sh: %s\n' "$*" >&2
    exit 1
}

log() {
    printf '\n==> %s\n' "$*"
}

while (($#)); do
    case "$1" in
        --quartus-root)
            (($# >= 2)) || die "--quartus-root requires a directory"
            QUARTUS_ROOT="$2"
            shift 2
            ;;
        --skip-packages)
            INSTALL_PACKAGES=0
            shift
            ;;
        --skip-udev)
            INSTALL_UDEV=0
            shift
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            die "unknown option: $1 (try --help)"
            ;;
    esac
done

[[ "$(uname -s)" == Linux ]] || die "this script currently supports Linux hosts only"
[[ "$(uname -m)" == x86_64 ]] || die "Intel Quartus requires an x86_64 host"
command -v apt-get >/dev/null || die "apt-get was not found; use an Ubuntu/Debian host"

run_as_root() {
    if ((EUID == 0)); then
        "$@"
    else
        command -v sudo >/dev/null || die "sudo is required for system setup"
        sudo "$@"
    fi
}

if ((INSTALL_PACKAGES)); then
    log "Installing FPGA, ARM cross-build, and debug dependencies"
    run_as_root apt-get update
    run_as_root apt-get install -y --no-install-recommends \
        build-essential cmake ninja-build make git git-lfs curl wget unzip \
        python3 python3-pip python3-venv device-tree-compiler \
        gcc-arm-linux-gnueabihf g++-arm-linux-gnueabihf binutils-arm-linux-gnueabihf \
        gdb-multiarch openocd minicom picocom screen \
        verilator iverilog gtkwave yosys \
        libncurses-dev libstdc++6 libx11-6 libxext6 libxft2 libxrender1 libxt6 \
        libusb-1.0-0 libudev1 udev
fi

if ((INSTALL_UDEV)); then
    log "Configuring non-root access to Intel/Altera USB-Blaster devices"
    rule_tmp="$(mktemp)"
    trap 'rm -f -- "${rule_tmp:-}"' EXIT
    printf '%s\n' \
        '# Intel/Altera USB-Blaster and USB-Blaster II' \
        'SUBSYSTEM=="usb", ATTR{idVendor}=="09fb", MODE="0660", GROUP="plugdev", TAG+="uaccess"' \
        >"$rule_tmp"
    run_as_root install -m 0644 "$rule_tmp" "$UDEV_RULE_FILE"
    run_as_root udevadm control --reload-rules
    run_as_root udevadm trigger --subsystem-match=usb
fi

# Locate common Quartus installations when no path was supplied.
if [[ -z "$QUARTUS_ROOT" ]]; then
    for candidate in \
        "$HOME/altera/25.1std/quartus" \
        "$HOME/altera_lite/25.1std/quartus" \
        "$HOME/intelFPGA_lite/25.1std/quartus" \
        /opt/altera/25.1std/quartus \
        /opt/altera_lite/25.1std/quartus \
        /opt/intelFPGA_lite/25.1std/quartus; do
        if [[ -x "$candidate/bin/quartus_sh" ]]; then
            QUARTUS_ROOT="$candidate"
            break
        fi
    done
fi

if [[ -n "$QUARTUS_ROOT" ]]; then
    QUARTUS_ROOT="$(cd -- "$QUARTUS_ROOT" && pwd)"
    [[ -x "$QUARTUS_ROOT/bin/quartus_sh" ]] || \
        die "no executable bin/quartus_sh below: $QUARTUS_ROOT"
fi

log "Writing ${ENV_FILE}"
{
    cat <<'EOF'
#!/usr/bin/env bash
# Generated by setup.sh. Source this file; do not execute it.
export CROSS_COMPILE=arm-linux-gnueabihf-
export ARCH=arm
EOF
    if [[ -n "$QUARTUS_ROOT" ]]; then
        printf 'export QUARTUS_ROOTDIR=%q\n' "$QUARTUS_ROOT"
        printf 'export PATH=%q/bin:%q/sopc_builder/bin:$PATH\n' "$QUARTUS_ROOT" "$QUARTUS_ROOT"
    fi
} >"$ENV_FILE"
chmod 0644 "$ENV_FILE"

log "Checking the toolchain"
for tool in arm-linux-gnueabihf-gcc dtc verilator iverilog; do
    if command -v "$tool" >/dev/null; then
        printf '  %-30s %s\n' "$tool" "$(command -v "$tool")"
    else
        printf '  %-30s %s\n' "$tool" "NOT FOUND"
    fi
done

if [[ -n "$QUARTUS_ROOT" ]]; then
    printf '  %-30s %s\n' quartus_sh "$QUARTUS_ROOT/bin/quartus_sh"
else
    cat <<'EOF'

Quartus was not found. Install Altera Quartus Prime Lite 25.1std with Cyclone V
device support, then rerun this script with --quartus-root. The current HPS
Linux flow uses Altera's GSRD source repositories, not the legacy SoC EDS.
EOF
fi

cat <<EOF

DE10-Nano host setup complete.
Run: source ${ENV_FILE}
If a USB-Blaster was already connected, unplug and reconnect it before use.
EOF
